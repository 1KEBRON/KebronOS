// Keep four physical pixels per 64px desktop icon; lossless WebP after resizing.
import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const names = ["disk", "folder-northstar", "folder-work", "mac", "preview", "readme", "trash-empty"].map((name) => `${name}.png`);
const imports: string[] = [];
const entries: string[] = [];
for (const name of names) {
  const source = `public/icons/macosx/${name}`;
  const target = name.replace(/\.png$/, ".webp");
  await sharp(source).resize(256, 256, { fit: "inside", withoutEnlargement: true })
    .webp({ lossless: true, effort: 6 }).toFile(`src/assets/desktop-icons/${target}`);
  const id = `icon${imports.length}`;
  imports.push(`import ${id} from "@/assets/desktop-icons/${target}";`);
  entries.push(`  "/icons/macosx/${name}": ${id},`);
}
await writeFile("src/utils/desktopIconAssets.ts", `// Generated by scripts/optimize-desktop-icons.ts. Original art remains available at full size.\n${imports.join("\n")}\n\nconst assets: Record<string, string> = {\n${entries.join("\n")}\n};\n\nexport function desktopIconAsset(path: string): string {\n  return assets[path] ?? path;\n}\n`);
